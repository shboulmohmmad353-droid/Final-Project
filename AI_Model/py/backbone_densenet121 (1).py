def process_data(path, label, fname):
    def _process(path_b, label_b, fname_b):
        path_str  = path_b.decode('utf-8')
        fname_str = fname_b.decode('utf-8')
        img = cv2.imread(path_str)
        if img is None:
            img = np.zeros((IMG_H, IMG_W, 3), dtype=np.uint8)
        else:
            img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
            img = cv2.resize(img, (IMG_W, IMG_H))
        lbl = np.float32(label_b)
        box = get_bbox(fname_str)
        msk = polygon_to_mask(fname_str, IMG_H, IMG_W)
        return img, lbl, box, msk

    img, lbl, box, msk = tf.numpy_function(
        _process, [path, label, fname],
        [tf.uint8, tf.float32, tf.float32, tf.float32])
    img.set_shape([IMG_H, IMG_W, 3])
    lbl.set_shape([])
    box.set_shape([4])
    msk.set_shape([IMG_H, IMG_W, 1])
    return img, lbl, box, msk

def augment_data(img, lbl, box, msk, weight, augment):
    def _aug(img_np, msk_np):
        msk_2d  = msk_np[:, :, 0]
        tfm     = aug_train(image=img_np, mask=msk_2d) if augment \
                  else aug_val(image=img_np, mask=msk_2d)
        aug_img = tfm['image'].astype(np.float32)
        aug_msk = tfm['mask'].astype(np.float32)[..., np.newaxis]
        return aug_img, aug_msk

    img_aug, msk_aug = tf.numpy_function(_aug, [img, msk], [tf.float32, tf.float32])
    img_aug.set_shape([IMG_H, IMG_W, 3])
    msk_aug.set_shape([IMG_H, IMG_W, 1])

    targets        = (lbl, msk_aug, box)
    sample_weights = (
        tf.cast(weight, tf.float32),
        tf.constant(1.0, dtype=tf.float32),
        tf.constant(1.0, dtype=tf.float32),
    )
    return img_aug, targets, sample_weights

def build_ds(data_list, augment=False, shuffle=False):
    paths   = [d['path']  for d in data_list]
    labels  = [d['label'] for d in data_list]
    fnames  = [d['fname'] for d in data_list]
    weights = [class_weight_dict.get(d['combined_label'], 1.0) for d in data_list]

    ds = tf.data.Dataset.from_tensor_slices((paths, labels, fnames, weights))
    if shuffle:
        ds = ds.shuffle(len(data_list), seed=SEED)
    ds = ds.map(lambda p, l, f, w: (*process_data(p, l, f), w),
                num_parallel_calls=tf.data.AUTOTUNE)
    ds = ds.cache()
    ds = ds.map(lambda img, lbl, box, msk, w: augment_data(img, lbl, box, msk, w, augment),
                num_parallel_calls=tf.data.AUTOTUNE)
    ds = ds.batch(BATCH_SIZE).prefetch(tf.data.AUTOTUNE)
    return ds

