    union        = np.sum(gt) + np.sum(pr) - intersection
    mean_iou  = (intersection + 1e-6) / (union + 1e-6)
    mean_dice = (2*intersection + 1e-6) / (np.sum(gt) + np.sum(pr) + 1e-6)
    print(f"\nSegmentation (Fractured only, n={len(frac_idx)}):")
    print(f"  Mean IoU   : {mean_iou:.4f}")
