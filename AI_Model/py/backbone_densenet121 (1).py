def build_fracturenet(freeze=True):
    inputs   = keras.Input(shape=(IMG_H, IMG_W, 3), name='input')
    backbone = DenseNet121(include_top=False, weights='imagenet', input_tensor=inputs)
    backbone.trainable = not freeze
    feat = backbone.output
    print(f"Backbone: DenseNet121 → feature shape: {feat.shape}")
    reg  = regularizers.l2(L2_REG)

    # Head 1: Classification
    cls = layers.GlobalAveragePooling2D()(feat)
    cls = layers.Dense(512, activation='relu', kernel_regularizer=reg)(cls)
    cls = layers.BatchNormalization()(cls)
    cls = layers.Dropout(0.55)(cls)
    cls = layers.Dense(128, activation='relu', kernel_regularizer=reg)(cls)
    cls = layers.Dropout(0.4)(cls)
    cls_out = layers.Dense(1, activation='sigmoid', dtype='float32', name='cls_out')(cls)

    # Head 2: Segmentation — 5× upsample 7→224
    seg = layers.Conv2DTranspose(512, 3, strides=2, padding='same')(feat)
    seg = layers.BatchNormalization()(seg); seg = layers.Activation('relu')(seg)
    seg = layers.Conv2DTranspose(256, 3, strides=2, padding='same')(seg)
    seg = layers.BatchNormalization()(seg); seg = layers.Activation('relu')(seg)
    seg = layers.Conv2DTranspose(128, 3, strides=2, padding='same')(seg)
    seg = layers.BatchNormalization()(seg); seg = layers.Activation('relu')(seg)
    seg = layers.Conv2DTranspose(64,  3, strides=2, padding='same')(seg)
    seg = layers.BatchNormalization()(seg); seg = layers.Activation('relu')(seg)
    seg = layers.Conv2DTranspose(32,  3, strides=2, padding='same')(seg)
    seg = layers.BatchNormalization()(seg); seg = layers.Activation('relu')(seg)
    seg = layers.Conv2D(16, 3, padding='same', activation='relu')(seg)
    seg = layers.Conv2D(8,  3, padding='same', activation='relu')(seg)
    seg_out = layers.Conv2D(1, 1, activation='sigmoid', dtype='float32', name='seg_out')(seg)

    # Head 3: Localization
    loc = layers.GlobalAveragePooling2D()(feat)
    loc = layers.Dense(256, activation='relu', kernel_regularizer=reg)(loc)
    loc = layers.BatchNormalization()(loc)
    loc = layers.Dropout(0.3)(loc)
    loc = layers.Dense(64, activation='relu', kernel_regularizer=reg)(loc)
    loc_out = layers.Dense(4, activation='sigmoid', dtype='float32', name='loc_out')(loc)

    return Model(inputs, [cls_out, seg_out, loc_out],
                 name='FractureNet_DenseNet121'), backbone

def compile_model(model, lr):
    model.compile(
        optimizer=keras.optimizers.Adam(lr),
        loss={
            'cls_out': focal_loss(gamma=2.0, alpha=0.35),
            'seg_out': dice_bce_loss(),
            'loc_out': 'mse',
        },
        loss_weights={'cls_out': 4.0, 'seg_out': 2.0, 'loc_out': 0.5},
        metrics={
            'cls_out': [keras.metrics.BinaryAccuracy(name='acc'),
                        keras.metrics.AUC(name='auc')],
            'seg_out': [seg_iou_metric, seg_dice_metric],
            'loc_out': ['mae'],
        }
    )

