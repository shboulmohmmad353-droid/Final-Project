#  13. LOSSES
def focal_loss(gamma=2.0, alpha=0.35):
    def loss_fn(y_true, y_pred):
        y_true  = tf.cast(y_true, tf.float32)
        y_pred  = tf.clip_by_value(y_pred, 1e-7, 1.0 - 1e-7)
        bce     = -y_true * tf.math.log(y_pred) - (1-y_true) * tf.math.log(1-y_pred)
        p_t     = y_true * y_pred + (1-y_true) * (1-y_pred)
        alpha_t = y_true * alpha  + (1-y_true) * (1-alpha)
        return tf.reduce_mean(alpha_t * tf.pow(1.0 - p_t, gamma) * bce)
    return loss_fn

def dice_bce_loss(smooth=1e-6):
    def loss_fn(y_true, y_pred):
        y_true = tf.cast(tf.reshape(y_true, [tf.shape(y_true)[0], -1]), tf.float32)
        y_pred = tf.cast(tf.reshape(y_pred, [tf.shape(y_pred)[0], -1]), tf.float32)
        y_pred = tf.clip_by_value(y_pred, 1e-7, 1.0 - 1e-7)
        intersection = tf.reduce_sum(y_true * y_pred, axis=1)
        union        = tf.reduce_sum(y_true, axis=1) + tf.reduce_sum(y_pred, axis=1)
        dice         = 1.0 - (2.0 * intersection + smooth) / (union + smooth)
        bce          = -tf.reduce_mean(
            y_true * tf.math.log(y_pred) + (1 - y_true) * tf.math.log(1 - y_pred), axis=1)
        return tf.reduce_mean(0.5 * dice + 0.5 * bce)
    return loss_fn

def seg_iou_metric(y_true, y_pred):
    y_true = tf.cast(y_true, tf.float32)
    y_pred = tf.cast(y_pred > SEG_THRESHOLD, tf.float32)
    intersection = tf.reduce_sum(y_true * y_pred)
    union        = tf.reduce_sum(y_true) + tf.reduce_sum(y_pred) - intersection
    return (intersection + 1e-6) / (union + 1e-6)

def seg_dice_metric(y_true, y_pred):
    y_true = tf.cast(y_true, tf.float32)
    y_pred = tf.cast(y_pred > SEG_THRESHOLD, tf.float32)
    intersection = 2.0 * tf.reduce_sum(y_true * y_pred)
    denom        = tf.reduce_sum(y_true) + tf.reduce_sum(y_pred)
    return (intersection + 1e-6) / (denom + 1e-6)

