def build_fracturenet(freeze=True, model_choice='EfficientNetB0'):
    inputs   = keras.Input(shape=(IMG_H, IMG_W, 3), name='input')

    backbone_map = {
        'EfficientNetB0': EfficientNetB0,
        'EfficientNetB3': EfficientNetB3,
        'EfficientNetB4': EfficientNetB4,
        'ResNet50V2'    : ResNet50V2,
        'DenseNet121'   : DenseNet121,
    }
    if model_choice not in backbone_map:
        raise ValueError(f" Backbone Unsupported: {model_choice}. "
                         f"Options: {list(backbone_map.keys())}")

    BackboneClass = backbone_map[model_choice]
    backbone = BackboneClass(include_top=False, weights='imagenet', input_tensor=inputs)
    backbone.trainable = not freeze
    feat = backbone.output
    print(f" Backbone: {model_choice} → feature shape: {feat.shape}")

    # Head 1: Classification
    cls = layers.GlobalAveragePooling2D()(feat)
    cls = layers.Dense(512, activation='relu')(cls)
    cls = layers.BatchNormalization()(cls)
    cls = layers.Dropout(0.45)(cls)
    cls = layers.Dense(128, activation='relu')(cls)
    cls = layers.Dropout(0.3)(cls)
    cls_out = layers.Dense(1, activation='sigmoid', dtype='float32', name='cls_out')(cls)

    # Head 2: Localization
    loc = layers.GlobalAveragePooling2D()(feat)
    loc = layers.Dense(256, activation='relu')(loc)
    loc = layers.BatchNormalization()(loc)
    loc = layers.Dropout(0.3)(loc)
    loc = layers.Dense(64, activation='relu')(loc)
    loc_out = layers.Dense(4, activation='sigmoid', dtype='float32', name='loc_out')(loc)

    # Head 3: Segmentation (5× upsample 7→224)
    seg = layers.Conv2DTranspose(512, 3, strides=2, padding='same', activation='relu')(feat)
    seg = layers.BatchNormalization()(seg)
    seg = layers.Conv2DTranspose(256, 3, strides=2, padding='same', activation='relu')(seg)
    seg = layers.BatchNormalization()(seg)
    seg = layers.Conv2DTranspose(128, 3, strides=2, padding='same', activation='relu')(seg)
    seg = layers.BatchNormalization()(seg)
    seg = layers.Conv2DTranspose(64,  3, strides=2, padding='same', activation='relu')(seg)
    seg = layers.BatchNormalization()(seg)
    seg = layers.Conv2DTranspose(32,  3, strides=2, padding='same', activation='relu')(seg)
    seg = layers.Conv2D(16, 3, padding='same', activation='relu')(seg)
    seg_out = layers.Conv2D(1, 1, activation='sigmoid', dtype='float32', name='seg_out')(seg)

    return Model(inputs, [cls_out, loc_out, seg_out], name=f'FractureNet_{model_choice}'), backbone

def compile_model(model, lr):
    model.compile(
        optimizer=keras.optimizers.Adam(lr),
        loss={'cls_out': 'binary_crossentropy',
              'loc_out': 'mse',
              'seg_out': 'binary_crossentropy'},
        loss_weights={'cls_out': 2.0, 'loc_out': 0.5, 'seg_out': 1.0},
        metrics={'cls_out': [keras.metrics.BinaryAccuracy(name='acc'),
                             keras.metrics.AUC(name='auc')],
                 'loc_out': ['mae'],
                 'seg_out': [keras.metrics.BinaryAccuracy(name='acc'),
                             keras.metrics.MeanIoU(num_classes=2, name='iou')]}
    )

