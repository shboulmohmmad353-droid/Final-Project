def normalize_images(folder, target_ext='.jpg', target_size=IMG_SIZE):
    converted = 0
    for fname in os.listdir(folder):
        fpath = os.path.join(folder, fname)
        ext = os.path.splitext(fname)[1].lower()
        if ext not in ['.jpg', '.jpeg', '.png', '.bmp', '.tiff', '.webp']:
            continue
        try:
            img = Image.open(fpath).convert('RGB')
            if ext != target_ext:
                new_path = os.path.splitext(fpath)[0] + target_ext
                img.save(new_path, 'JPEG', quality=95)
                os.remove(fpath)
                converted += 1
        except Exception as e:
            print(f"  Skipping {fname}: {e}")
    print(f"  Converted {converted} files in {os.path.basename(folder)}")

