# 12. HELPER FUNCTIONS
def polygon_to_mask(fname, h, w):
    mask = np.zeros((h, w), dtype=np.float32)
    if fname not in fname_to_anns:
        return mask[..., np.newaxis]
    for ann in fname_to_anns[fname]:
        sx = w / ann['orig_w']
        sy = h / ann['orig_h']
        for seg in ann['segmentation']:
            pts = np.array(seg, dtype=np.float32).reshape(-1, 2)
            pts[:, 0] *= sx
            pts[:, 1] *= sy
            cv2.fillPoly(mask, [pts.astype(np.int32)], 1.0)
    return mask[..., np.newaxis]

def get_bbox(fname):
    if fname not in fname_to_anns:
        return np.array([0., 0., 0., 0.], dtype=np.float32)
    ann = fname_to_anns[fname][0]
    x, y, w, h = ann['bbox']
    ow, oh = ann['orig_w'], ann['orig_h']
    return np.array([(x+w/2)/ow, (y+h/2)/oh, w/ow, h/oh], dtype=np.float32)

